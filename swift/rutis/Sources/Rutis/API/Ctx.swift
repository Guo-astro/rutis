import Foundation

extension Rutis {
    /// What `apply` receives: the plugin's handle on rutis. Plugin code
    /// passes no context anywhere else: the call chain travels with the
    /// Task (a task-local), and the row's Tasks are cancelled when it
    /// unloads.
    public final class Ctx: @unchecked Sendable {
        let runtime: Runtime
        let row: Row

        init(runtime: Runtime, row: Row) {
            self.runtime = runtime
            self.row = row
        }

        /// The project directory the host gave this runtime.
        public var project: String { runtime.project }

        /// This row's scope chain, outermost first; empty at the root.
        public var scope: [Scope] { row.scope }

        /// The service `name`, which `inject` must list, as the protocol
        /// `P` (generated by `@RutisClient`) proxies it. A provider in this
        /// process whose object implements the protocol gives the object
        /// itself. Each method of the proxy must be one the service has.
        public func use<P: RutisProxy>(_ name: String, _: P.Type) throws -> P.Service {
            let (client, local) = try runtime.client(row, name)
            if let local, let object = local as? P.Service { return object }
            for method in P.rutisMethodNames where client.methods[method] == nil {
                throw RutisError(name: "Error", message: "use \(name): \(P.self) calls \(method), which the service does not have")
            }
            return P.rutisMake(client)
        }

        /// The service `name`, which `inject` must list, called by method
        /// name.
        public func use(_ name: String) throws -> Client {
            try runtime.client(row, name).0
        }

        /// Provides `service` (an instance of a @RutisService type) as
        /// `name` until the plugin unloads or the returned function is
        /// called. Declared in `provides`, it offers the declared methods;
        /// otherwise it is announced to rutis with its methods, all `async`.
        /// A name another plugin of this process provides fails the load.
        @discardableResult
        public func provide(_ name: String, _ service: RutisExportable) -> () -> Void {
            runtime.provide(row, name, service)
        }

        /// Runs `cleanup` when the plugin unloads, latest first.
        public func effect(_ cleanup: @escaping () async throws -> Void) {
            runtime.lock.withLock { row.cleanups.append(cleanup) }
        }

        /// Runs `task` in a Task of its own, with the call chain: its error
        /// is written to stderr; when the plugin unloads, it is cancelled
        /// and the unload waits for it.
        public func spawn(_ task: @escaping () async throws -> Void) {
            row.spawn(task)
        }

        // ── Events ───────────────────────────────────────────────────

        /// Listens to the event `name` on the bus until the plugin unloads
        /// or the returned function is called. The listener's parameters
        /// are the event's arguments, decoded by their types (missing ones
        /// nil, extra ones ignored); in a waterfall its last parameter is a
        /// `Rutis.Next`. Its result counts in `serial`, `bail` and
        /// `waterfall`: nil and false are no result.
        @discardableResult
        public func on<each A, R>(_ name: String, prepend: Bool = false, global: Bool = false,
                                  _ listener: @escaping (repeat each A) async throws -> R) -> () -> Void
        {
            runtime.listen(row, name, prepend: prepend, global: global, listenerBody(name, listener))
        }

        /// Starts every listener of `name` and returns at once. A listener's
        /// failure never reaches the emitter: it is reported where the
        /// listener is. Throws only for an emission refused outright (a
        /// reserved name, arguments that cannot cross).
        public func emit(_ name: String, _ args: Any?...) throws {
            try Emitter(ctx: self, keep: nil).emit(name, args)
        }

        /// Starts every listener of `name` and waits for all; failures are
        /// a RutisError named AggregateError with them in registration order.
        public func parallel(_ name: String, _ args: Any?...) async throws {
            try await Emitter(ctx: self, keep: nil).parallel(name, args)
        }

        /// Runs the listeners of `name` one at a time and returns the first
        /// result (anything but nil and false), decoded into `R`.
        public func serial<R>(_ name: String, _ args: Any?..., as type: R.Type) async throws -> R? {
            try await Emitter(ctx: self, keep: nil).serial(name, args, as: type)
        }

        /// `serial`, its result as a value of type `Any`.
        public func serial(_ name: String, _ args: Any?...) async throws -> Any? {
            try await Emitter(ctx: self, keep: nil).serial(name, args, as: Any.self) ?? nil
        }

        /// Calls the outermost listener of `name`, which gets `next` as its
        /// last parameter: `next` runs the rest of the chain, and at its end
        /// `terminal`, called with the event's arguments. Returns the
        /// outermost listener's value as it is.
        public func waterfall<R, each T, TR>(_ name: String, _ args: Any?..., as type: R.Type,
                                             terminal: @escaping (repeat each T) async throws -> TR) async throws -> R?
        {
            try await Emitter(ctx: self, keep: nil).waterfall(name, args, as: type, terminal: Emitter.terminal(terminal))
        }

        /// `waterfall` without a terminal: the last `next` gives no result.
        public func waterfall<R>(_ name: String, _ args: Any?..., as type: R.Type) async throws -> R? {
            try await Emitter(ctx: self, keep: nil).waterfall(name, args, as: type, terminal: nil)
        }

        /// `serial` as a synchronous call on the wire: listeners elsewhere
        /// run as synchronous calls (a wait cycle fails with
        /// SyncWaitCycle), and an asynchronous listener of another language
        /// fails it with AsyncListener. The Task waits without a thread.
        public func bail<R>(_ name: String, _ args: Any?..., as type: R.Type) async throws -> R? {
            try await Emitter(ctx: self, keep: nil).bail(name, args, as: type)
        }

        /// `emit` with the arguments in an array.
        public func emit(_ name: String, arguments: [Any?]) throws {
            try Emitter(ctx: self, keep: nil).emit(name, arguments)
        }

        /// `parallel` with the arguments in an array.
        public func parallel(_ name: String, arguments: [Any?]) async throws {
            try await Emitter(ctx: self, keep: nil).parallel(name, arguments)
        }

        /// `serial` with the arguments in an array.
        public func serial<R>(_ name: String, arguments: [Any?], as type: R.Type) async throws -> R? {
            try await Emitter(ctx: self, keep: nil).serial(name, arguments, as: type)
        }

        /// `bail` with the arguments in an array.
        public func bail<R>(_ name: String, arguments: [Any?], as type: R.Type) async throws -> R? {
            try await Emitter(ctx: self, keep: nil).bail(name, arguments, as: type)
        }

        /// `waterfall` with the arguments in an array; `terminal` gets them as
        /// an array too.
        public func waterfall<R>(_ name: String, arguments: [Any?], as type: R.Type,
                                 terminal: (([Any?]) async throws -> Any?)? = nil) async throws -> R?
        {
            try await Emitter(ctx: self, keep: nil).waterfall(name, arguments, as: type, terminal: terminal.map(Emitter.terminal(arguments:)))
        }

        /// An emitter whose dispatches reach only the listeners `keep`
        /// accepts (listeners registered `global` excepted). `keep` runs in
        /// this process, once per listener, before any listener runs; its
        /// error fails the dispatch.
        public func filter(_ keep: @escaping (Listener) async throws -> Bool) -> Emitter {
            Emitter(ctx: self, keep: keep)
        }
    }

    /// Emits events, filtered: `ctx.filter` makes one.
    public struct Emitter: @unchecked Sendable {
        let ctx: Ctx
        let keep: ((Listener) async throws -> Bool)?

        public func emit(_ name: String, _ args: Any?...) throws { try emit(name, args) }

        public func parallel(_ name: String, _ args: Any?...) async throws { try await parallel(name, args) }

        public func serial<R>(_ name: String, _ args: Any?..., as type: R.Type) async throws -> R? {
            try await serial(name, args, as: type)
        }

        public func waterfall<R, each T, TR>(_ name: String, _ args: Any?..., as type: R.Type,
                                             terminal: @escaping (repeat each T) async throws -> TR) async throws -> R?
        {
            try await waterfall(name, args, as: type, terminal: Emitter.terminal(terminal))
        }

        public func waterfall<R>(_ name: String, _ args: Any?..., as type: R.Type) async throws -> R? {
            try await waterfall(name, args, as: type, terminal: nil)
        }

        public func bail<R>(_ name: String, _ args: Any?..., as type: R.Type) async throws -> R? {
            try await bail(name, args, as: type)
        }

        public func emit(_ name: String, arguments: [Any?]) throws { try emit(name, arguments) }

        public func parallel(_ name: String, arguments: [Any?]) async throws { try await parallel(name, arguments) }

        public func serial<R>(_ name: String, arguments: [Any?], as type: R.Type) async throws -> R? {
            try await serial(name, arguments, as: type)
        }

        public func bail<R>(_ name: String, arguments: [Any?], as type: R.Type) async throws -> R? {
            try await bail(name, arguments, as: type)
        }

        public func waterfall<R>(_ name: String, arguments: [Any?], as type: R.Type,
                                 terminal: (([Any?]) async throws -> Any?)? = nil) async throws -> R?
        {
            try await waterfall(name, arguments, as: type, terminal: terminal.map(Emitter.terminal(arguments:)))
        }

        static func terminal(arguments body: @escaping ([Any?]) async throws -> Any?) -> ([Value]) async throws -> Value {
            { args in try ValueCodec.encodeAny(try await body(args.map(ValueCodec.native)) as Any) }
        }

        static func terminal<each T, TR>(_ body: @escaping (repeat each T) async throws -> TR) -> ([Value]) async throws -> Value {
            { args in
                var index = 0
                func argument<X>(_: X.Type) throws -> X {
                    defer { index += 1 }
                    return try Arguments(args).decode(index, as: X.self)
                }
                return try ValueCodec.encode(try await body(repeat try argument((each T).self)))
            }
        }

        func encoded(_ args: [Any?]) throws -> [Value] { try args.map { try ValueCodec.encodeAny($0 as Any) } }

        func emit(_ name: String, _ args: [Any?]) throws {
            _ = try ctx.runtime.emitNow(ctx.row, name, try encoded(args), keep: keep)
        }

        func parallel(_ name: String, _ args: [Any?]) async throws {
            _ = try await ctx.runtime.dispatch(ctx.row, name, .parallel, try encoded(args), keep: keep, terminal: nil)
        }

        func serial<R>(_ name: String, _ args: [Any?], as _: R.Type) async throws -> R? {
            let value = try await ctx.runtime.dispatch(ctx.row, name, .serial, try encoded(args), keep: keep, terminal: nil)
            return try Emitter.result(value, R.self)
        }

        func waterfall<R>(_ name: String, _ args: [Any?], as _: R.Type, terminal: (([Value]) async throws -> Value)?) async throws -> R? {
            let value = try await ctx.runtime.dispatch(ctx.row, name, .waterfall, try encoded(args), keep: keep, terminal: terminal)
            return try Emitter.result(value, R.self)
        }

        func bail<R>(_ name: String, _ args: [Any?], as _: R.Type) async throws -> R? {
            let value = try await ctx.runtime.dispatch(ctx.row, name, .bail, try encoded(args), keep: keep, terminal: nil)
            return try Emitter.result(value, R.self)
        }

        static func result<R>(_ value: Value, _: R.Type) throws -> R? {
            if value.isNullish { return nil }
            return try ValueCodec.decode(R.self, from: value)
        }
    }
}

/// A listener as the runtime calls it: the event's arguments and, in a
/// waterfall, `next`.
package typealias ListenerBody = (_ args: [Value], _ next: NextFunction?) async throws -> Value

/// Whether a parameter type is `Rutis.Next<R>` or `Rutis.Next<R>?`.
func nextType(_ type: Any.Type) -> (NextConstructible.Type, optional: Bool)? {
    if let next = type as? NextConstructible.Type { return (next, false) }
    if let optional = type as? OptionalProtocol.Type, let next = optional.wrappedType as? NextConstructible.Type { return (next, true) }
    return nil
}

/// A listener closure as the runtime calls it: its parameters decoded by
/// their types from the event's arguments, `next` as its last parameter in a
/// waterfall (when that parameter is a `Rutis.Next`).
package func listenerBody<each A, R>(_ name: String, _ listener: @escaping (repeat each A) async throws -> R) -> ListenerBody {
    var types: [Any.Type] = []
    repeat types.append((each A).self)
    let lastIsNext = types.last.map { nextType($0) != nil } ?? false
    let count = types.count
    return { args, next in
        var values = args
        if let next, lastIsNext {
            // `next` is the last parameter, whatever the arguments.
            values = Array(args.prefix(count - 1))
            while values.count < count - 1 { values.append(.undefined) }
            values.append(.function(SessionFunction { _ in try await next() }))
        }
        var index = 0
        func argument<T>(_: T.Type) throws -> T {
            defer { index += 1 }
            if let (made, optional) = nextType(T.self) {
                let value = index < values.count ? values[index] : .undefined
                if let next = made.make(from: value) {
                    return (optional ? (T.self as! OptionalProtocol.Type).rutisSome(next) : next) as! T
                }
                guard optional else {
                    throw RutisError(name: "Error", message: "listener of \(name): no next in this dispatch (not a waterfall)")
                }
                return (T.self as! OptionalProtocol.Type).rutisNone as! T
            }
            return try Rutis.Arguments(values).decode(index, as: T.self)
        }
        let result = try await listener(repeat try argument((each A).self))
        return try ValueCodec.encode(result)
    }
}
