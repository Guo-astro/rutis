import Foundation

/// A plugin: the services it uses (`inject`), those it provides (optional
/// `provides`), its configuration type, and `apply`, which starts it.
///
/// ```swift
/// let weather = Rutis.define(Plugin(
///     name: "weather",
///     inject: ["llm"],
///     config: Config.self,
///     apply: { ctx, config in
///         let llm = try ctx.use("llm", LLMProxy.self)
///         ctx.provide("weather", Weather(llm: llm, city: config.city))
///     }))
/// ```
///
/// What `ctx.provide` provides reaches rutis by itself, its methods all
/// `async`; `provides` marks methods `sync` and tells `rutis-host check`
/// what the plugin provides before it runs.
public struct Plugin<Config: Decodable> {
    /// The plugin's name in its binary: rows name it `swift:<name>`, and it
    /// is the `plugin` of its listeners' descriptors.
    public var name: String
    /// The services it uses: it runs only while all are there.
    public var inject: [String]
    /// The services it provides and their methods (optional).
    public var provides: [String: Rutis.Advanced.Shape]
    /// Its version, if its author gives one (the manifest's `version`).
    public var version: String?
    /// Starts the plugin. An error fails the load; the cleanups registered
    /// so far run.
    public var apply: (Rutis.Ctx, Config) async throws -> Void

    public init(name: String, inject: [String] = [], provides: [String: Rutis.Advanced.Shape] = [:], version: String? = nil,
                config _: Config.Type, apply: @escaping (Rutis.Ctx, Config) async throws -> Void)
    {
        self.name = name
        self.inject = inject
        self.provides = provides
        self.version = version
        self.apply = apply
    }
}

extension Plugin where Config == Rutis.NoConfig {
    /// A plugin without configuration.
    public init(name: String, inject: [String] = [], provides: [String: Rutis.Advanced.Shape] = [:], version: String? = nil,
                apply: @escaping (Rutis.Ctx) async throws -> Void)
    {
        self.init(name: name, inject: inject, provides: provides, version: version, config: Rutis.NoConfig.self) { ctx, _ in
            try await apply(ctx)
        }
    }
}

/// A configuration type that gives its JSON Schema: `@RutisConfig` derives
/// it from the stored properties, or write `static let rutisSchema`.
public protocol RutisConfigurable {
    static var rutisSchema: Rutis._Generated.Schema { get }
}

extension Rutis {
    /// The configuration of a plugin that takes none.
    public struct NoConfig: Codable, Sendable {
        public init() {}
        public init(from _: Decoder) throws {}
        public func encode(to _: Encoder) throws {}
    }
}

extension Rutis.Advanced {
    /// Whether a method is called synchronously (the caller waits) or
    /// asynchronously.
    public enum MethodKind: String, Sendable {
        case sync
        case async
    }

    /// The methods a provided service declares, each `sync` or `async`.
    public struct Shape: ExpressibleByDictionaryLiteral, Sendable {
        package let kinds: [String: MethodKind]
        /// The method names of the type, when the shape names one (checked
        /// by `define`).
        let known: [String]?
        let type: String?

        public init(dictionaryLiteral elements: (String, MethodKind)...) {
            kinds = Dictionary(elements, uniquingKeysWith: { $1 })
            known = nil
            type = nil
        }

        init(kinds: [String: MethodKind], known: [String]?, type: String?) {
            self.kinds = kinds
            self.known = known
            self.type = type
        }

        /// The methods of `T` (a @RutisService type), `async` unless `sync`
        /// names them.
        public static func of<T: RutisExportable>(_ type: T.Type, sync: [String] = []) -> Shape {
            var kinds: [String: MethodKind] = [:]
            for name in T.rutisMethodNames { kinds[name] = .async }
            for name in sync { kinds[name] = .sync }
            return Shape(kinds: kinds, known: T.rutisMethodNames, type: String(describing: T.self))
        }
    }
}

extension Rutis._Generated {
    /// A configuration's JSON Schema.
    public struct Schema: @unchecked Sendable {
        package let json: JSON

        package init(_ json: JSON) { self.json = json }

        /// A schema written as JSON text. Invalid text is a programming
        /// error.
        public init(json text: String) {
            do {
                json = try JSONReader.parse(text)
            } catch {
                preconditionFailure("rutis: invalid JSON Schema text: \(error)")
            }
        }

        /// `{"type": "object"}`: any object, checked only when decoded.
        public static let anyObject = Schema(.object([("type", .string("object"))]))

        /// An object schema of `properties` (generated by `@RutisConfig`).
        public static func object(_ properties: [Property]) -> Schema {
            var fields: [(String, JSON)] = []
            var required: [JSON] = []
            for property in properties {
                var schema = property.schema.json
                if let description = property.description, case var .object(inner) = schema {
                    inner.append(("description", .string(description)))
                    schema = .object(inner)
                }
                if let fallback = property.defaultJSON, case var .object(inner) = schema {
                    guard let value = try? JSONReader.parse(fallback) else {
                        preconditionFailure("rutis: \(property.name): its default is not JSON: \(fallback)")
                    }
                    inner.append(("default", value))
                    schema = .object(inner)
                }
                fields.append((property.name, schema))
                if property.required { required.append(.string(property.name)) }
            }
            var out: [(String, JSON)] = [("type", .string("object")), ("properties", .object(fields))]
            if !required.isEmpty { out.append(("required", .array(required))) }
            return Schema(.object(out))
        }

        /// A property of an object schema.
        public struct Property {
            public var name: String
            public var schema: Schema
            public var required: Bool
            public var description: String?
            /// Its `default`, as JSON text (`@RutisConfig`'s literal initial
            /// value).
            public var defaultJSON: String?
            public init(_ name: String, _ schema: Schema, required: Bool, description: String? = nil) {
                self.name = name
                self.schema = schema
                self.required = required
                self.description = description
            }

            /// A property with a literal default (`@RutisConfig`'s `var units
            /// = "metric"`): not required when the default has a JSON form
            /// (one without, a `Character`, is no default).
            public init(_ name: String, _ schema: Schema, required: Bool, description: String? = nil, default defaultJSON: String?) {
                self.init(name, schema, required: required && defaultJSON == nil, description: description)
                self.defaultJSON = defaultJSON
            }
        }

        /// The schema of a stored property's type `T`: strings, integers,
        /// floats, booleans, arrays, string-keyed dictionaries, nested
        /// configuration types, String-valued enums; `{}` for any other.
        public static func of<T>(_ type: T.Type) -> Schema { Schema(schema(of: type, depth: 0)) }

        /// The JSON text of a literal default (what `@RutisConfig` writes
        /// for `var units = "metric"`).
        /// `nil` for a value with no JSON form (a `Character`, say): the
        /// property then has no default and stays required.
        public static func literal<T>(_ value: T) -> String? {
            guard let encoded = try? ValueCodec.encodeAny(value), let json = jsonOf(encoded) else { return nil }
            return String(decoding: JSONWriter.write(json), as: UTF8.self)
        }

        /// A literal's value as JSON: sets as arrays, decimals and big
        /// integers as their numbers; `nil` for what JSON has no form of.
        static func jsonOf(_ value: Value) -> JSON? {
            switch value {
            case let .data(json): return json
            case let .list(items), let .set(items):
                var out: [JSON] = []
                for item in items {
                    guard let json = jsonOf(item) else { return nil }
                    out.append(json)
                }
                return .array(out)
            case let .record(fields):
                var out: [(String, JSON)] = []
                for (key, item) in fields {
                    guard let json = jsonOf(item) else { return nil }
                    out.append((key, json))
                }
                return .object(out)
            case let .decimal(text): return .number(text)
            case let .bigint(big): return .number(big.description)
            default: return nil
            }
        }

        /// Whether a property of type `T` may be left out.
        public static func isOptional<T>(_: T.Type) -> Bool { T.self is OptionalProtocol.Type }

        static func schema(of type: Any.Type, depth: Int) -> JSON {
            func typed(_ name: String) -> JSON { .object([("type", .string(name))]) }
            if depth > 32 { return .object([]) }
            if let configurable = type as? RutisConfigurable.Type { return configurable.rutisSchema.json }
            if let optional = type as? OptionalProtocol.Type { return schema(of: optional.wrappedType, depth: depth + 1) }
            switch type {
            case is String.Type, is URL.Type, is UUID.Type: return typed("string")
            case is Bool.Type: return typed("boolean")
            case is Int.Type, is Int8.Type, is Int16.Type, is Int32.Type, is Int64.Type,
                 is UInt.Type, is UInt8.Type, is UInt16.Type, is UInt32.Type, is UInt64.Type:
                return typed("integer")
            case is Double.Type, is Float.Type, is Decimal.Type: return typed("number")
            default: break
            }
            if let array = type as? SchemaArray.Type {
                return .object([("type", .string("array")), ("items", schema(of: array.schemaElement, depth: depth + 1))])
            }
            if let dictionary = type as? SchemaDictionary.Type, dictionary.schemaKeyIsString {
                return .object([("type", .string("object")),
                                ("additionalProperties", schema(of: dictionary.schemaValue, depth: depth + 1))])
            }
            if let cases = type as? any CaseIterable.Type {
                let values = cases.allCases.compactMap { ($0 as? any RawRepresentable)?.rawValue as? String }
                if !values.isEmpty {
                    return .object([("type", .string("string")), ("enum", .array(values.map(JSON.string)))])
                }
            }
            return .object([])
        }
    }
}

protocol SchemaArray {
    static var schemaElement: Any.Type { get }
}

extension Array: SchemaArray {
    static var schemaElement: Any.Type { Element.self }
}

protocol SchemaDictionary {
    static var schemaKeyIsString: Bool { get }
    static var schemaValue: Any.Type { get }
}

extension Dictionary: SchemaDictionary {
    static var schemaKeyIsString: Bool { Key.self == String.self }
    static var schemaValue: Any.Type { Value.self }
}

extension Rutis {
    /// A defined plugin, to serve in a binary or host in an app.
    public final class Definition: @unchecked Sendable {
        public let name: String
        let inject: [String]
        let provides: [String: Rutis.Advanced.Shape]
        package let schema: JSON
        let version: String?
        let api: Int
        let apply: (Ctx, Value) async throws -> Void

        init(name: String, inject: [String], provides: [String: Rutis.Advanced.Shape], schema: JSON, version: String?, api: Int,
             apply: @escaping (Ctx, Value) async throws -> Void)
        {
            self.name = name
            self.inject = inject
            self.provides = provides
            self.schema = schema
            self.version = version
            self.api = api
            self.apply = apply
        }

        /// What the plugin declares, as `rows.schema` answers it and the
        /// manifest lists it.
        var described: JSON {
            .object([
                ("config", schema),
                ("inject", .array(inject.map(JSON.string))),
                ("provides", .object(provides.sorted { $0.key < $1.key }.map { name, shape in
                    (name, .object(shape.kinds.sorted { $0.key < $1.key }.map { ($0.key, .string($0.value.rawValue)) }))
                })),
                ("version", version.map(JSON.string) ?? .null),
                // Every plugin of this SDK may provide services `provides`
                // does not list: they reach rutis by themselves.
                ("announces", .bool(true)),
            ])
        }
    }

    /// Checks a plugin's declarations and makes it servable. A declaration
    /// that cannot work stops the program at start, naming it.
    public static func define<C: Decodable>(_ plugin: Plugin<C>) -> Definition {
        precondition(!plugin.name.isEmpty && !plugin.name.contains(where: { ":/\0".contains($0) }),
                     "rutis: invalid plugin name \"\(plugin.name)\"")
        for (name, shape) in plugin.provides {
            precondition(!name.contains("#") && !name.contains("\0"), "rutis: plugin \(plugin.name): service name \"\(name)\" cannot be projected")
            if let known = shape.known {
                for method in shape.kinds.keys where !known.contains(method) {
                    preconditionFailure("rutis: plugin \(plugin.name): provides \(name): \(shape.type ?? "the type") has no method \(method)")
                }
            }
        }
        // The schema the host checks rows with (`check`): the type's own
        // (`@RutisConfig`, `rutisSchema`), or what its type says (a `String`
        // config: `{"type": "string"}`); a type that says nothing more takes
        // any object.
        let schema: JSON
        if C.self == NoConfig.self {
            schema = .null
        } else if let configurable = C.self as? RutisConfigurable.Type {
            schema = configurable.rutisSchema.json
        } else if case var .object(fields) = Rutis._Generated.Schema.of(C.self).json, !fields.isEmpty {
            // An optional config type takes no config too.
            if C.self is OptionalProtocol.Type, let index = fields.firstIndex(where: { $0.0 == "type" }), case let .string(type) = fields[index].1 {
                fields[index].1 = .array([.string(type), .string("null")])
                if let at = fields.firstIndex(where: { $0.0 == "enum" }), case let .array(values) = fields[at].1 {
                    fields[at].1 = .array(values + [.null])
                }
            }
            schema = .object(fields)
        } else {
            schema = Rutis._Generated.Schema.anyObject.json
        }
        let apply = plugin.apply
        return Definition(name: plugin.name, inject: plugin.inject, provides: plugin.provides, schema: schema,
                          version: plugin.version, api: Rutis.Advanced.pluginAPI)
        { ctx, config in
            // The host validated the config and filled its defaults; a
            // decoder error is the schema and the type disagreeing (§3.3).
            let value = config
            let decoded: C
            do {
                decoded = try ValueCodec.decode(C.self, from: value.isNullish ? .data(.object([])) : value)
            } catch let problem as ConfigProblem {
                throw ConfigSchema.error([ConfigSchema.issue(problem.path, problem.reason)])
            } catch {
                throw ConfigSchema.error([ConfigSchema.issue(ConfigSchema.path(of: error), "is not a value the plugin accepts")])
            }
            try await apply(ctx, decoded)
        }
    }
}
