//! The loader as the service `loader`, for plugins of every language: add
//! a row, reload its code, remove it, read the state (the design "The host
//! writes its own plugins", #185). The same name and shapes as Cordis's
//! `ctx.loader`; Rust plugins keep using [`Loader`] itself.

use serde::Deserialize;
use serde_json::Value;

use super::status::Status;
use super::{EntryStatus, Loader, NewEntry};
use crate::error::Failure;
use crate::LoaderError;

/// What `LoaderPlugin` provides by name as `loader`.
pub(crate) struct LoaderService(pub(crate) Loader);

/// A row for `create`, written as a row of `rutis.json` is.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct RowOptions {
    /// Generated by the loader (8 hex digits) when absent.
    #[serde(default)]
    pub id: Option<String>,
    pub name: String,
    #[serde(default)]
    pub config: Value,
    #[serde(default)]
    pub disabled: bool,
    #[serde(default)]
    pub inject: Vec<String>,
}

/// What a `loader` method throws: its message is what rutis prints for
/// people (which row, why, where); `row` is the row it is about.
#[derive(Debug, serde::Serialize)]
pub struct Error {
    row: String,
    #[serde(skip)]
    message: String,
}

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.message)
    }
}

impl std::error::Error for Error {}

impl Error {
    fn new(row: &str, message: String) -> Self {
        Self {
            row: row.to_owned(),
            message,
        }
    }
}

#[rutis::service(name = "loader")]
impl LoaderService {
    /// Add a row and start it; its id, generated (8 hex digits) when
    /// `options` has none. All or nothing: a row that cannot start is not
    /// left behind.
    pub async fn create(
        &self,
        options: RowOptions,
        parent: Option<String>,
        position: Option<usize>,
    ) -> Result<String, Error> {
        // The id now, so a failure names the row it would have been.
        let id = match options.id {
            Some(id) => id,
            None => super::api::generate_id(|id| self.0.get(id).is_some()),
        };
        let entry = NewEntry {
            id: Some(id.clone()),
            name: options.name,
            config: options.config,
            disabled: options.disabled,
            inject: options.inject,
            ..NewEntry::default()
        };
        match self.0.create(entry, parent.as_deref(), position).await {
            Ok((id, _)) => Ok(id),
            Err(error) => Err(Error::new(&id, edit_failed(&id, "added", &error))),
        }
    }

    /// Load the row's code again, as [`Loader::reload`]: when the new
    /// code cannot load, the previous version keeps running; when it fails
    /// in `apply`, the row fails with it.
    pub async fn reload(&self, id: String) -> Result<(), Error> {
        match self.0.reload(&id).await {
            Ok(_) => Ok(()),
            Err(error @ LoaderError::UnknownEntry(_)) => Err(Error::new(&id, error.to_string())),
            Err(error) => {
                // Whether it runs, once the rows are reconciled again.
                self.0.settled().await;
                let running = self.0.get(&id).is_some_and(|entry| active(&entry.status));
                Err(Error::new(&id, cannot_reload(&id, &error, running)))
            }
        }
    }

    /// Unload the row and remove it.
    pub async fn remove(&self, id: String) -> Result<(), Error> {
        self.0
            .remove(&id)
            .await
            .map_err(|error| Error::new(&id, edit_failed(&id, "removed", &error)))
    }

    /// The state now: rows, services, runtimes, calls in progress; what
    /// `rutis-host status` prints.
    pub fn status(&self) -> Status {
        self.0.status()
    }
}

/// Whether a row runs: its plugin is active.
fn active(status: &EntryStatus) -> bool {
    matches!(status, EntryStatus::Running(snapshot) if snapshot.state == rutis::host::FiberState::Active)
}

/// The text of an edit of row `id` that failed: each line names the row.
/// `done` is what the edit did when only storing it failed.
fn edit_failed(id: &str, done: &str, error: &LoaderError) -> String {
    let named = |line: &str| match line.starts_with(&format!("{id}: ")) {
        true => line.to_owned(),
        false => format!("{id}: {line}"),
    };
    match error {
        // Said of no row but the one named.
        LoaderError::NoEditableLayer | LoaderError::RowExists(_) | LoaderError::UnknownEntry(_) => {
            error.to_string()
        }
        LoaderError::PersistFailed(why) => format!("{id}: {done}, but {why}"),
        LoaderError::ApplyFailed { failures } => failures
            .iter()
            .map(|failure| failure.to_string())
            .collect::<Vec<_>>()
            .join("\n"),
        error => error
            .to_string()
            .lines()
            .map(named)
            .collect::<Vec<_>>()
            .join("\n"),
    }
}

/// `<id>: cannot reload: <why>`, and `; the previous version keeps
/// running` when it does (`running`). `error` names the rows that failed
/// with the new code first, the row itself when it is the one. A config
/// error is a line per problem, each named.
pub fn cannot_reload(id: &str, error: &LoaderError, running: bool) -> String {
    let failed = |failures: &[Failure]| -> String {
        failures
            .iter()
            .map(|failure| match failure.id == id {
                true => failure.error.clone(),
                false => format!("{} failed with it: {}", failure.id, failure.error),
            })
            .collect::<Vec<_>>()
            .join("; ")
    };
    let why = match error {
        LoaderError::ApplyFailed { failures } => failed(failures),
        LoaderError::RollbackFailed { apply, rollback } => {
            // The row itself failing on: its line says it does not run.
            let others: Vec<String> = rollback
                .iter()
                .filter(|failure| failure.id != id)
                .map(|failure| format!("{} still fails: {}", failure.id, failure.error))
                .collect();
            match others.is_empty() {
                true => failed(apply),
                false => format!(
                    "{}; with the previous {id} back, {}",
                    failed(apply),
                    others.join("; ")
                ),
            }
        }
        error => error.to_string(),
    };
    let problems: Vec<&str> = why.lines().collect();
    let config = problems.len() > 1 && problems.iter().all(|line| line.starts_with("config: "));
    let lines = match config {
        true => problems
            .iter()
            .map(|line| format!("{id}: cannot reload: {line}"))
            .collect::<Vec<_>>()
            .join("\n"),
        false => format!("{id}: cannot reload: {why}"),
    };
    match running {
        true => format!("{lines}; the previous version keeps running"),
        false => lines,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// guarantee: host/dev-reload
    /// The row that failed with another's new code comes first in the line,
    /// and whether the previous version runs on is said.
    #[test]
    fn a_failed_reload_names_the_row_that_failed() {
        let failure = |id: &str, error: &str| Failure {
            id: id.into(),
            error: error.into(),
        };
        let apply = LoaderError::ApplyFailed {
            failures: vec![failure("weather", "SyntaxError")],
        };
        assert_eq!(
            cannot_reload("llm", &apply, true),
            "llm: cannot reload: weather failed with it: SyntaxError; the previous version keeps running"
        );
        assert_eq!(
            cannot_reload("weather", &apply, false),
            "weather: cannot reload: SyntaxError"
        );
        let rollback = LoaderError::RollbackFailed {
            apply: vec![failure("weather", "SyntaxError")],
            rollback: vec![failure("weather", "SyntaxError")],
        };
        assert_eq!(
            cannot_reload("llm", &rollback, true),
            "llm: cannot reload: weather failed with it: SyntaxError; with the previous llm back, weather still fails: SyntaxError; the previous version keeps running"
        );
        // Its own apply failing, the row fails on: no more than its error.
        let own = LoaderError::RollbackFailed {
            apply: vec![failure("weather", "Error: boom")],
            rollback: vec![failure("weather", "Error: boom")],
        };
        assert_eq!(
            cannot_reload("weather", &own, false),
            "weather: cannot reload: Error: boom"
        );
    }

    /// guarantee: loader/service
    /// An edit that took effect but was not stored, and one the host keeps
    /// no editable configuration for, say so in the words of §7 of the
    /// design.
    #[test]
    fn an_edit_that_failed_says_what_happened_to_the_row() {
        assert_eq!(
            edit_failed(
                "weather",
                "added",
                &LoaderError::PersistFailed("rutis.json could not be written: denied".into())
            ),
            "weather: added, but rutis.json could not be written: denied"
        );
        assert_eq!(
            edit_failed("weather", "removed", &LoaderError::NoEditableLayer),
            "this host keeps no editable configuration, so rows cannot be added or removed"
        );
        let failure = |id: &str, error: &str| Failure {
            id: id.into(),
            error: error.into(),
        };
        let apply = LoaderError::ApplyFailed {
            failures: vec![failure("weather", "KeyError: 'units'"), failure("llm", "x")],
        };
        assert_eq!(
            edit_failed("weather", "added", &apply),
            "weather: KeyError: 'units'\nllm: x"
        );
        assert_eq!(
            edit_failed(
                "wether",
                "added",
                &LoaderError::NotFound {
                    name: "py:wether".into()
                }
            ),
            "wether: no plugin named \"py:wether\""
        );
    }
}
